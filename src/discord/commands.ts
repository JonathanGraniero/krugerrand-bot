import { EPHEMERAL, InteractionResponseType, type Interaction, type InteractionResponse } from "./types";
import { editOriginalResponse, type Embed } from "./api";
import { KRUGERRAND_PREMIUM, getGoldPrice, krugerrandPrice } from "../gold";
import { getKrugerrandFact } from "../facts";
import type { Env } from "../env";

const GOLD = 0xffd700;
const RED = 0xff0000;
/** Installable to servers and to users, usable in servers, DMs and group DMs. */
const EVERYWHERE = { integration_types: [0, 1], contexts: [0, 1, 2] };

/** Slash command definitions, uploaded to Discord by scripts/register-commands.ts. */
export const COMMANDS = [
  { name: "goldprice", description: "Get the current price of gold per troy ounce", ...EVERYWHERE },
  { name: "krugerrandprice", description: "Get the current price of a 1 oz Krugerrand", ...EVERYWHERE },
  { name: "krugerrandfact", description: "Get a random fact about Krugerrands", ...EVERYWHERE },
] as const;

type CommandName = (typeof COMMANDS)[number]["name"];

const HANDLERS: Record<CommandName, (env: Env) => Promise<Embed>> = {
  goldprice: goldPriceEmbed,
  krugerrandprice: krugerrandPriceEmbed,
  krugerrandfact: factEmbed,
};

/**
 * Every command calls an outside API, which can take longer than the 3 seconds
 * Discord waits for an answer. So answer straight away ("thinking…") and post
 * the result in the background.
 */
export function handleCommand(interaction: Interaction, env: Env, ctx: ExecutionContext): InteractionResponse {
  const name = interaction.data?.name ?? "";
  const handler = HANDLERS[name as CommandName];
  if (!handler) {
    return {
      type: InteractionResponseType.CHANNEL_MESSAGE_WITH_SOURCE,
      data: { content: `Unknown command: ${name}`, flags: EPHEMERAL },
    };
  }

  ctx.waitUntil(
    (async () => {
      let embed: Embed;
      try {
        embed = await handler(env);
      } catch (err) {
        console.error(`/${name} failed`, err);
        embed = errorEmbed("Something went wrong. Please try again later.");
      }
      await editOriginalResponse(interaction.application_id, interaction.token, { embeds: [embed] });
    })(),
  );
  return { type: InteractionResponseType.DEFERRED_CHANNEL_MESSAGE_WITH_SOURCE };
}

const usd = (n: number) => `$${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

async function goldPriceEmbed(): Promise<Embed> {
  const gold = await getGoldPrice();
  if (!gold) return errorEmbed("Unable to fetch the gold price right now. Please try again later.");
  return {
    title: "💰 Current Gold Price",
    color: GOLD,
    description: `**${usd(gold.price)} USD** per troy ounce`,
    timestamp: gold.updatedAt,
    footer: { text: `Spot price from ${gold.source}` },
  };
}

async function krugerrandPriceEmbed(): Promise<Embed> {
  const gold = await getGoldPrice();
  if (!gold) return errorEmbed("Unable to fetch the Krugerrand price right now. Please try again later.");
  const premium = `${(KRUGERRAND_PREMIUM * 100).toFixed(0)}%`;
  return {
    title: "🪙 Krugerrand Price (1 oz)",
    color: GOLD,
    description: `**${usd(krugerrandPrice(gold.price))} USD**`,
    fields: [
      { name: "Spot Gold", value: usd(gold.price), inline: true },
      { name: "Premium", value: premium, inline: true },
    ],
    timestamp: gold.updatedAt,
    footer: { text: `Estimate: spot from ${gold.source} plus a typical ${premium} dealer premium` },
  };
}

async function factEmbed(env: Env): Promise<Embed> {
  const fact = await getKrugerrandFact(env.HUGGINGFACE_API_KEY);
  return {
    title: "📚 Krugerrand Fact",
    color: GOLD,
    description: fact.text,
    footer: { text: fact.ai ? "Generated by AI, may contain mistakes" : "Did you know?" },
  };
}

function errorEmbed(description: string): Embed {
  return { title: "❌ Error", color: RED, description };
}
