import { afterEach, beforeAll, describe, expect, it, vi } from "vitest";
import { CURATED_FACTS } from "../src/facts";
import { createTestBot, lastEmbed, stubFetch, type TestBot } from "./helpers/discord";

const GOLD_API = "api.gold-api.com";
const SWISSQUOTE = "swissquote.com";
const HF = "router.huggingface.co";

const goldApi = (price: unknown) => () =>
  Response.json({ currency: "USD", name: "Gold", price, symbol: "XAU", updatedAt: "2026-09-30T23:34:18Z" });
const swissquote = () =>
  Response.json([
    {
      topo: { platform: "SwissquoteLtd", server: "Live5" },
      spreadProfilePrices: [{ spreadProfile: "premium", bid: 4150, ask: 4152 }],
      ts: 1790811265494,
    },
  ]);
const chat = (content: string) => () =>
  Response.json({ choices: [{ index: 0, message: { role: "assistant", content } }] });

let bot: TestBot;

beforeAll(async () => {
  bot = await createTestBot({ HUGGINGFACE_API_KEY: "hf_test" });
  vi.spyOn(console, "error").mockImplementation(() => {});
});

afterEach(() => {
  vi.unstubAllGlobals();
});

describe("/goldprice", () => {
  it("posts the live spot price", async () => {
    const net = stubFetch([[GOLD_API, goldApi(4155.200195)]]);
    await bot.command("goldprice");
    expect(lastEmbed(net)).toMatchObject({
      title: "💰 Current Gold Price",
      description: "**$4,155.20 USD** per troy ounce",
      timestamp: "2026-09-30T23:34:18Z",
      footer: { text: "Spot price from gold-api.com" },
    });
  });

  it("falls back to Swissquote when gold-api.com is down", async () => {
    const net = stubFetch([
      [GOLD_API, () => new Response("oops", { status: 503 })],
      [SWISSQUOTE, swissquote],
    ]);
    await bot.command("goldprice");
    expect(lastEmbed(net)).toMatchObject({
      description: "**$4,151.00 USD** per troy ounce",
      footer: { text: "Spot price from Swissquote" },
    });
  });

  it.each([["a non-number", "4155"], ["an implausible number", 3.5]])("ignores %s from a source", async (_, price) => {
    const net = stubFetch([[GOLD_API, goldApi(price)], [SWISSQUOTE, swissquote]]);
    await bot.command("goldprice");
    expect(lastEmbed(net).footer?.text).toBe("Spot price from Swissquote");
  });

  it("posts an error when every source fails", async () => {
    const net = stubFetch([
      [GOLD_API, () => Promise.reject(new TypeError("network down"))],
      [SWISSQUOTE, () => new Response("<html>", { status: 200 })],
    ]);
    await bot.command("goldprice");
    expect(lastEmbed(net)).toMatchObject({ title: "❌ Error" });
  });
});

describe("/krugerrandprice", () => {
  it("adds the 3% premium to spot", async () => {
    const net = stubFetch([[GOLD_API, goldApi(4000)]]);
    await bot.command("krugerrandprice");
    expect(lastEmbed(net)).toMatchObject({
      description: "**$4,120.00 USD**",
      fields: [
        { name: "Spot Gold", value: "$4,000.00" },
        { name: "Premium", value: "3%" },
      ],
    });
  });

  it("posts an error when the price is unavailable", async () => {
    const net = stubFetch([
      [GOLD_API, () => new Response("", { status: 500 })],
      [SWISSQUOTE, () => new Response("", { status: 500 })],
    ]);
    await bot.command("krugerrandprice");
    expect(lastEmbed(net).description).toContain("Krugerrand price");
  });
});

describe("/krugerrandfact", () => {
  it("posts the model's fact without cutting it at a decimal point", async () => {
    const fact = "Krugerrands are 91.67% gold. The rest is copper, which makes them harder.";
    const net = stubFetch([[HF, chat(`  **${fact}**\n`)]]);
    await bot.command("krugerrandfact");
    expect(lastEmbed(net)).toMatchObject({ description: fact, footer: { text: "Generated by AI, may contain mistakes" } });
  });

  it("sends the Hugging Face key and a chat request", async () => {
    const net = stubFetch([[HF, chat("The Krugerrand was first minted in 1967 in South Africa.")]]);
    await bot.command("krugerrandfact");
    const req = net.calls[0]!;
    expect(req.headers.get("Authorization")).toBe("Bearer hf_test");
    const body = (await req.json()) as { model: string; messages: { role: string }[] };
    expect(body.messages.map((m) => m.role)).toEqual(["system", "user"]);
  });

  it("retries on any provider when Groq fails", async () => {
    let n = 0;
    const net = stubFetch([
      [HF, () => (n++ === 0 ? new Response("model overloaded", { status: 503 }) : chat("Krugerrands have no face value printed on them.")())],
    ]);
    await bot.command("krugerrandfact");
    const models = await Promise.all(net.calls.slice(0, 2).map(async (r) => ((await r.json()) as { model: string }).model));
    expect(models).toEqual(["openai/gpt-oss-120b:groq", "openai/gpt-oss-120b"]);
    expect(lastEmbed(net).description).toBe("Krugerrands have no face value printed on them.");
  });

  it("uses a curated fact when every model fails", async () => {
    const net = stubFetch([[HF, () => new Response("", { status: 401 })]]);
    await bot.command("krugerrandfact");
    const embed = lastEmbed(net);
    expect(CURATED_FACTS).toContain(embed.description);
    expect(embed.footer?.text).toBe("Did you know?");
  });

  it("uses a curated fact without calling out when there is no key", async () => {
    const keyless = await createTestBot();
    const net = stubFetch([]);
    await keyless.command("krugerrandfact");
    expect(net.calls).toHaveLength(1); // only the Discord edit
    expect(CURATED_FACTS).toContain(lastEmbed(net).description);
  });
});
